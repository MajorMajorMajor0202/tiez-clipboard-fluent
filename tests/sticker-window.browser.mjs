import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createServer } from 'vite';
import { chromium } from 'playwright';

const server = await createServer({ cacheDir: 'node_modules/.cache/sticker-tests-vite', server: { host: '127.0.0.1', port: 0 } });
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
  const context = await browser.newContext({ viewport: { width: 320, height: 180 }, screen: { width: 1920, height: 1080 } });
  const errors = [];
  const open = async kind => {
    const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/tests/sticker-window.fixture.html?id=1&kind=${kind}`);
    await page.locator('.sticker-header').waitFor();
    await page.waitForFunction(() => window.stickerTest.commands.some(value => value.command === 'plugin:window|set_size'));
    return page;
  };
  const text = await open('text');
  await text.getByRole('button', { name: '编辑文本', exact: true }).waitFor({ state: 'visible' });
  const initial = await text.locator('.sticker-inline-text').boundingBox();
  const body = await text.locator('.sticker-body').boundingBox();
  const sizeCalls = await text.evaluate(() => window.stickerTest.commands.filter(value => value.command === 'plugin:window|set_size').length);
  await text.locator('.sticker-inline-text').evaluate(node => { node.dataset.sameNode = 'yes'; });
  await text.getByRole('button', { name: '编辑文本', exact: true }).click();
  const editor = text.getByRole('textbox', { name: '编辑贴图文本' });
  assert.deepEqual(await editor.boundingBox(), initial, 'editing uses the original text box geometry');
  assert.deepEqual(await text.locator('.sticker-body').boundingBox(), body);
  assert.equal(await editor.getAttribute('data-same-node'), 'yes', 'editing retains the display element');
  assert.equal(await text.locator('textarea').count(), 0);
  await editor.fill('原位编辑后的内容\n第二行');
  await editor.press('Control+Enter');
  await text.getByRole('button', { name: '编辑文本', exact: true }).waitFor();
  assert.equal(await text.locator('.sticker-inline-text').innerText(), '原位编辑后的内容\n第二行');
  assert.equal(await text.evaluate(() => window.stickerTest.commands.filter(value => value.command === 'plugin:window|set_size').length), sizeCalls, 'saving cannot resize a manually adjusted window');
  await text.getByRole('button', { name: '编辑文本', exact: true }).click();
  await editor.fill('取消的修改'); await editor.press('Escape');
  assert.equal(await text.locator('.sticker-inline-text').innerText(), '原位编辑后的内容\n第二行');
  await text.evaluate(() => window.stickerTest.failSave(true));
  await text.getByRole('button', { name: '编辑文本', exact: true }).click();
  await editor.fill('保存失败仍保留的草稿'); await editor.press('Control+Enter');
  await text.getByRole('alert').waitFor();
  assert.equal(await editor.innerText(), '保存失败仍保留的草稿');
  await text.evaluate(() => window.stickerTest.failSave(false));
  await editor.press('Control+Enter');
  await text.getByRole('button', { name: '编辑文本', exact: true }).waitFor();
  assert.equal(await text.locator('.sticker-header').evaluate(node => getComputedStyle(node).borderBottomWidth), '0px');

  await text.evaluate(() => window.stickerTest.settings({ 'app.theme': 'acrylic', 'app.color_mode': 'dark' }));
  await text.waitForFunction(() => document.documentElement.classList.contains('theme-acrylic') && document.documentElement.classList.contains('dark-mode'));
  await text.evaluate(() => window.stickerTest.settings({ 'app.theme': 'acrylic', 'app.color_mode': 'light', 'app.sticker_backdrop_mode': 'mica' }));
  await text.waitForFunction(() => document.documentElement.classList.contains('theme-mica') && document.documentElement.classList.contains('light-mode'));
  assert.equal(await text.evaluate(() => window.stickerTest.commands.some(value => value.command === 'set_theme')), false, 'sticker cannot mutate the main window theme');
  await text.evaluate(() => { localStorage.setItem('tiez_sticker_backdrop_mode', 'mica'); return window.stickerTest.settings({ 'app.theme': 'acrylic', 'app.color_mode': 'light' }); });
  await text.waitForFunction(() => document.documentElement.classList.contains('theme-acrylic'));

  const image = await open('image');
  assert.deepEqual(await image.evaluate(() => window.stickerTest.fitStickerImage(40, 20, 1920, 1080)), { width: 128, height: 64 }, 'small images keep their ratio at an operable minimum size');
  await image.locator('.sticker-thumbnail img').waitFor();
  assert.equal(await image.locator('.sticker-file-name').count(), 1, 'images default to file cards');
  const thumb = await image.locator('.sticker-thumbnail').boundingBox();
  assert.equal(thumb.width, 56); assert.equal(thumb.height, 56);
  await image.getByRole('button', { name: '切换为整张图片', exact: true }).click();
  await image.waitForFunction(() => window.stickerTest.commands.filter(value => value.command === 'plugin:window|set_size').at(-1).payload.value.Logical?.width === 640);
  const size = await image.evaluate(() => window.stickerTest.commands.filter(value => value.command === 'plugin:window|set_size').at(-1).payload.value.Logical);
  assert.deepEqual(size, { width: 640, height: 360 }, 'initial image sizing keeps its ratio within the default cap');
  assert.equal(await image.evaluate(() => window.stickerTest.commands.filter(value => value.command === 'plugin:window|set_max_size').at(-1).payload.value), null, 'manual resizing has no maximum constraint');
  await image.setViewportSize({ width: 640, height: 360 });
  await image.mouse.move(400, 200);
  await image.waitForFunction(() => getComputedStyle(document.querySelector('.sticker-header')).opacity === '0');
  await image.mouse.move(200, 10);
  await image.waitForFunction(() => getComputedStyle(document.querySelector('.sticker-header')).opacity === '1');
  await mkdir('artifacts/sticker-window', { recursive: true });
  await image.mouse.move(400, 200);
  await image.waitForFunction(() => getComputedStyle(document.querySelector('.sticker-header')).opacity === '0');
  await image.screenshot({ path: 'artifacts/sticker-window/image-mode.png' });
  await image.setViewportSize({ width: 900, height: 720 });
  const after = await image.evaluate(() => window.stickerTest.commands.filter(value => value.command === 'plugin:window|set_size').length);
  await image.evaluate(() => window.stickerTest.settings({ 'app.theme': 'mica', 'app.color_mode': 'dark' }));
  await image.waitForFunction(() => document.documentElement.classList.contains('dark-mode'));
  assert.equal(await image.evaluate(() => window.stickerTest.commands.filter(value => value.command === 'plugin:window|set_size').length), after, 'theme changes cannot reset user resizing');
  await image.mouse.move(200, 10);
  await image.getByRole('button', { name: '切换为文件卡片', exact: true }).click();
  await image.locator('.sticker-thumbnail').waitFor();
  await image.setViewportSize({ width: 320, height: 140 });
  await image.evaluate(() => { window.stickerTest.failMaterial(true); return window.stickerTest.settings({ 'app.theme': 'acrylic', 'app.color_mode': 'dark' }); });
  await image.waitForFunction(() => !document.documentElement.dataset.stickerNativeBackdrop);
  const fallback = await image.locator('.sticker-card').evaluate(node => getComputedStyle(node).backgroundColor);
  assert.equal(fallback, 'rgba(32, 32, 32, 0.88)', 'unavailable native material keeps a readable background');
  await image.screenshot({ path: 'artifacts/sticker-window/card-mode.png' });
  await image.setViewportSize({ width: 64, height: 100 });
  await image.getByRole('button', { name: '切换为整张图片', exact: true }).click();
  await image.mouse.move(32, 10);
  const narrow = await image.getByRole('button', { name: '切换为文件卡片', exact: true }).boundingBox();
  assert.ok(narrow.x >= 0 && narrow.x + narrow.width <= 64, 'tiny image windows keep the mode control accessible');
  const file = await open('file');
  assert.equal(await file.locator('.sticker-file-name').textContent(), '测试文档.pdf');
  assert.equal(await file.getByRole('button', { name: '切换为整张图片', exact: true }).count(), 0);
  assert.deepEqual(errors, []);
  console.log('Sticker browser checks passed: theme sync/override/reset, scoped native material, inline save/cancel/retry, stable geometry, default file cards, image ratio/cap, hover header and unlimited manual resizing.');
} finally { await browser?.close(); await server.close(); }
