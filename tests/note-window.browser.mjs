import assert from 'node:assert/strict';
import { createServer, build, preview } from 'vite';
import { chromium } from 'playwright';
import { resolve } from 'node:path';
import { mkdir } from 'node:fs/promises';
const production = process.argv.includes('--release');
const config = { cacheDir: 'node_modules/.cache/note-tests-vite', build: { outDir: 'artifacts/note-production', rollupOptions: { input: resolve('tests/note-window.fixture.html') } } };
if (production) await build(config);
const server = production ? await preview({ ...config, preview: { host: '127.0.0.1', port: 0 } }) : await createServer({ ...config, server: { host: '127.0.0.1', port: 0 } });
let browser;
try {
  if (!production) await server.listen();
  browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
  const page = await browser.newPage({ viewport: { width: 320, height: 380 } });
  page.setDefaultTimeout(10000);
  await mkdir('artifacts/notes', { recursive: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  if (production) await page.route('**/*', async route => {
    if (route.request().resourceType() !== 'document') return route.continue();
    const response = await route.fetch();
    const body = (await response.text()).replace(/<style\b/g, '<style nonce="tiez-release-test"');
    await route.fulfill({ response, body, headers: { ...response.headers(), 'content-security-policy': "style-src 'self' 'unsafe-inline' 'nonce-tiez-release-test'" } });
  });
  const url = `http://127.0.0.1:${server.httpServer.address().port}/tests/note-window.fixture.html?id=1`;
  await page.goto(url);
  const surface = page.locator('.sticky-note-surface');
  const editor = page.locator('.ProseMirror');
  await editor.waitFor();
  await page.waitForFunction(() => document.documentElement.dataset.noteNativeBackdrop === 'true');
  await page.getByTitle('取消置顶', { exact: true }).waitFor();
  const normal = await surface.boundingBox();
  assert.equal(normal.height, 380, 'window surface fills the viewport despite imported manager card CSS');
  await surface.hover();
  assert.deepEqual(await surface.boundingBox(), normal, 'hover cannot move or shrink the window surface');
  assert.equal(await surface.evaluate(el => getComputedStyle(el).transform), 'none');
  const material = await surface.evaluate(el => getComputedStyle(el).backgroundColor);
  assert.equal(material, 'rgba(248, 248, 248, 0.22)', 'successful native material uses a light webview tint');
  assert.equal(await page.evaluate(() => window.noteTest.commands.some(c => c.command === 'set_theme')), false, 'note theme cannot mutate main theme');
  const body = await page.locator('.note-body').boundingBox();
  const text = await editor.boundingBox();
  const hide = async () => {
    await page.mouse.move(0, 0);
    await page.locator('.note-window-root').dispatchEvent('mouseout', { relatedTarget: null });
    await page.evaluate(() => window.dispatchEvent(new Event('blur')));
    await page.waitForFunction(() => getComputedStyle(document.querySelector('.note-titlebar')).opacity === '0');
  };
  await hide();
  assert.deepEqual(await page.locator('.note-body').boundingBox(), body);
  assert.deepEqual(await editor.boundingBox(), text, 'hiding controls cannot move or resize markdown text');
  await page.locator('.note-window-root').dispatchEvent('mouseover', { relatedTarget: null });
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.note-titlebar')).opacity === '1');
  assert.deepEqual(await editor.boundingBox(), text);
  await page.screenshot({ path: 'artifacts/notes/window.png' });
  for (const width of [220, 320]) {
    await page.setViewportSize({ width, height: 380 });
    const buttons = await page.locator('.note-titlebar button').evaluateAll(nodes => nodes.map(el => { const r = el.getBoundingClientRect(); return { x: r.x, right: r.right, y: r.y, width: r.width, height: r.height }; }));
    assert.equal(buttons.length, 6);
    for (const b of buttons) { assert.equal(b.width, 32); assert.equal(b.height, 32); assert.ok(b.x >= 0 && b.right <= width); assert.equal(b.y, buttons[0].y); }
  }
  await page.getByTitle('切换为 Markdown 源码模式', { exact: true }).click();
  const source = page.locator('textarea');
  await source.waitFor();
  const sourceRect = await source.boundingBox();
  await hide();
  assert.deepEqual(await source.boundingBox(), sourceRect, 'source editor also retains its geometry');
  await page.locator('.note-window-root').dispatchEvent('mouseover', { relatedTarget: null });
  const draft = '# 这是一条很长很长的便笺标题，用来检查折叠和停靠时的省略效果\n\n没有保存完的草稿也应保留';
  await source.fill(draft);
  await source.evaluate(el => { el.dataset.sameEditor = 'yes'; });
  await page.getByTitle('折叠便笺', { exact: true }).click();
  await page.locator('.note-mode-collapsed').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  assert.equal(await source.isVisible(), false);
  assert.equal(await page.locator('.note-compact-title').innerText(), draft.split('\n')[0].slice(2));
  assert.equal(await page.getByTitle('便笺设置与背景颜色', { exact: true }).count(), 0, 'collapsed bar omits editing controls');
  await page.setViewportSize({ width: 320, height: 34 });
  await page.screenshot({ path: 'artifacts/notes/collapsed.png' });
  await page.evaluate(() => window.noteTest.action('collapse'));
  await page.locator('.note-mode-expanded').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  await page.setViewportSize({ width: 320, height: 380 });
  assert.equal(await source.getAttribute('data-same-editor'), 'yes');
  assert.equal(await source.inputValue(), draft);
  assert.equal(await page.locator('.note-body').getAttribute('hidden'), null, 'text returns once the resize has completed');
  await page.getByTitle('取消置顶', { exact: true }).click();
  await page.getByTitle('置顶便笺', { exact: true }).waitFor();
  await page.evaluate(() => window.noteTest.holdResize());
  await page.getByTitle('停靠到屏幕右侧', { exact: true }).click();
  assert.ok(await page.evaluate(() => window.noteTest.commands.filter(c => c.command === 'plugin:window|set_always_on_top').at(-1).payload.value), 'docking pins a previously unpinned note');
  await page.locator('.note-mode-docked').waitFor();
  assert.equal(await page.locator('.note-body').getAttribute('hidden'), '', 'shrinking hides the editor before native resize frames');
  assert.equal(await source.getAttribute('data-same-editor'), 'yes');
  await page.evaluate(() => window.noteTest.releaseResize());
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  await page.locator('.note-window-root').dispatchEvent('mouseout', { relatedTarget: null });
  await page.waitForFunction(() => window.noteTest.commands.filter(c => c.command === 'plugin:window|set_position').at(-1).payload.value.Physical.x === 1700);
  const docking = await page.evaluate(() => window.noteTest.commands.filter(c => c.command === 'plugin:window|set_position').at(-1).payload.value);
  assert.deepEqual(docking, { Physical: { x: 1700, y: 501 } }, 'title stays visible while close button extends beyond the work area');
  assert.equal(await page.locator('.note-dock-capsule > button').last().getAttribute('title'), '关闭 (保存)');
  assert.equal(await page.locator('.note-dock-title').evaluate(el => getComputedStyle(el).textOverflow), 'ellipsis');
  await page.setViewportSize({ width: 264, height: 38 });
  await page.screenshot({ path: 'artifacts/notes/docked.png' });
  assert.equal(await surface.evaluate(el => getComputedStyle(el).borderTopLeftRadius), '8px');
  assert.equal(await surface.evaluate(el => getComputedStyle(el).borderTopRightRadius), '0px');
  const beforePeek = await page.evaluate(() => window.noteTest.commands.length);
  await page.locator('.note-window-root').dispatchEvent('mouseover', { relatedTarget: null });
  await page.waitForFunction(() => window.noteTest.commands.filter(c => c.command === 'plugin:window|set_position').at(-1).payload.value.Physical.x === 1668);
  assert.ok(await page.evaluate(start => window.noteTest.commands.slice(start).some(c => c.command === 'plugin:window|set_position' && c.payload.value.Physical.x > 1668 && c.payload.value.Physical.x < 1700), beforePeek), 'hover moves through intermediate native positions');
  await page.locator('.note-window-root').dispatchEvent('mouseout', { relatedTarget: null });
  await page.waitForFunction(() => window.noteTest.commands.filter(c => c.command === 'plugin:window|set_position').at(-1).payload.value.Physical.x === 1700);
  await page.locator('.note-window-root').dispatchEvent('mouseover', { relatedTarget: null });
  await page.waitForFunction(() => { const x = window.noteTest.commands.filter(c => c.command === 'plugin:window|set_position').at(-1).payload.value.Physical.x; return x > 1668 && x < 1700; });
  await page.evaluate(() => window.noteTest.holdResize());
  await page.getByRole('button', { name: '展开便笺', exact: true }).click();
  await page.locator('.note-mode-expanded').waitFor();
  assert.equal(await page.locator('.note-body').evaluate(el => getComputedStyle(el).display), 'none', 'expanding keeps text out of layout until its final viewport');
  assert.equal(await source.getAttribute('data-same-editor'), 'yes');
  await page.evaluate(() => window.noteTest.releaseResize());
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  const afterRestore = await page.evaluate(() => window.noteTest.commands.length);
  await page.waitForTimeout(230);
  assert.equal(await page.evaluate(start => window.noteTest.commands.slice(start).filter(c => c.command === 'plugin:window|set_position').length, afterRestore), 0, 'cancelled hover frames cannot move the restored window');
  await page.getByTitle('取消置顶', { exact: true }).waitFor();
  await page.setViewportSize({ width: 320, height: 380 });
  assert.equal(await source.inputValue(), draft);
  assert.equal(await page.locator('.note-body').getAttribute('hidden'), null, 'text returns once the resize has completed');
  await page.evaluate(() => window.noteTest.action('collapse'));
  await page.locator('.note-mode-collapsed').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  await page.evaluate(() => window.noteTest.action('dock'));
  await page.locator('.note-mode-docked').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  await page.evaluate(() => window.noteTest.action('dock'));
  await page.locator('.note-mode-collapsed').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  await page.evaluate(() => window.noteTest.action('collapse'));
  await page.locator('.note-mode-expanded').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  await page.evaluate(() => window.noteTest.moved({ x: 1600, y: 200 }));
  await page.waitForTimeout(300);
  assert.equal(await page.locator('.note-mode-expanded').count(), 1, 'moving to the right edge never docks automatically');
  await page.getByTitle('停靠到屏幕右侧', { exact: true }).click();
  await page.locator('.note-mode-docked').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  await page.waitForTimeout(280);
  await page.setViewportSize({ width:264, height:150 });
  const dockTitle = await page.locator('.note-dock-title').boundingBox();
  await page.mouse.move(dockTitle.x + 30, dockTitle.y + 15);
  await page.mouse.down();
  await page.mouse.move(dockTitle.x + 30, dockTitle.y + 85, { steps:5 });
  await page.mouse.up();
  await page.waitForFunction(() => window.noteTest.commands.some(c => c.command === 'move_docked_note' && c.payload.y > 35));
  assert.equal(await page.locator('.note-mode-docked').count(), 1, 'dropping a dragged title cannot expand the note');
  await page.evaluate(() => window.noteTest.action('dock'));
  await page.locator('.note-mode-expanded').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  assert.deepEqual(await page.evaluate(() => window.noteTest.dockNoteBounds({ x: -1920, y: 0, width: 1920, height: 1040 }, 1.5, 2000)), { x: -330, y: 983, width: 396, height: 57 });
  await page.setViewportSize({ width:320, height:380 });
  const dragCount = await page.evaluate(() => window.noteTest.commands.filter(c => c.command === 'plugin:window|start_dragging').length);
  await page.locator('.note-titlebar-drag').dblclick();
  await page.locator('.note-mode-collapsed').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  assert.equal(await page.evaluate(() => window.noteTest.commands.filter(c => c.command === 'plugin:window|start_dragging').length), dragCount, 'double click cannot begin native dragging');
  await page.locator('.note-titlebar-drag').dblclick();
  await page.locator('.note-mode-expanded').waitFor();
  await page.locator('.note-window-root[aria-busy="false"]').waitFor();
  const short = await page.evaluate(() => window.noteTest.dockNoteBounds({x:0,y:0,width:1920,height:1040}, 1, 200, 45));
  assert.deepEqual(short, { x:1840, y:200, width:124, height:38 });
  await page.getByTitle('便笺设置与背景颜色', { exact: true }).click();
  await page.getByTitle('便笺黄 (Yellow)', { exact: true }).click();
  await page.waitForFunction(() => window.noteTest.commands.some(c => c.command === 'set_note_backdrop' && c.payload.theme === 'solid'));
  assert.equal(await page.locator('.note-theme-yellow').evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(255, 249, 196)');
  await page.goto(url + '&failMaterial=1');
  await editor.waitFor();
  assert.equal(await page.locator('.note-theme-acrylic').evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(248, 248, 248, 0.9)', 'unavailable native material uses readable fallback');
  await page.goto(url + '&manager=1');
  const card = page.locator('.note-manager-card');
  await card.waitFor();
  await page.mouse.move(0, 0);
  await page.screenshot({ path: 'artifacts/notes/manager.png' });
  const cardRect = await card.boundingBox();
  await card.hover();
  assert.deepEqual(await card.boundingBox(), cardRect, 'manager cards have no hover elevation');
  assert.equal(await card.evaluate(el => getComputedStyle(el).transform), 'none');
  await page.getByRole('textbox', { name: '搜索便笺' }).fill('不存在的便笺');
  await page.getByText('未找到匹配的便笺').waitFor();
  await page.getByRole('button', { name: '清除搜索' }).click();
  await card.waitFor();
  await page.getByRole('button', { name: '新建便笺', exact: true }).click();
  assert.ok(await page.evaluate(() => window.noteTest.commands.some(c => c.command === 'create')));
  assert.deepEqual(errors, []);
  console.log('Notes: isolated styles, native material/fallback, fixed text geometry, narrow titlebar and neutral manager passed.');
} finally { await browser?.close(); await server.close(); }
